function pageLink(page: WikiPageKey): string {
  return `[${SYNTHETIC_WIKI_PAGE_TITLES[page]}](${wikiPagePath(SYNTHETIC_WIKI_PAGE_IDS[page])})`;
}

type WikiPageDefinition = Pick<
  Prisma.WikiPageCreateManyInput,
  "title" | "kind" | "whenToUse" | "sortOrder" | "markdown"
> & { id: string };

function knowledge(page: WikiPageKey, sortOrder: number, lines: readonly string[]): WikiPageDefinition {
  return {
    id: SYNTHETIC_WIKI_PAGE_IDS[page],
    title: SYNTHETIC_WIKI_PAGE_TITLES[page],
    kind: "knowledge",
    whenToUse: null,
    sortOrder,
    markdown: lines.join("\n"),
  };
}

function procedure(
  page: WikiPageKey,
  sortOrder: number,
  whenToUse: string,
  lines: readonly string[],
): WikiPageDefinition {
  return { ...knowledge(page, sortOrder, lines), kind: "procedure", whenToUse };
}

